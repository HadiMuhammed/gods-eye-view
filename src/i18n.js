export function setLocale(locale, options = {}) {
  const resolved = resolveLocale(locale);
  currentLocale = resolved;

  const storage = options.storage ?? (typeof localStorage !== 'undefined' ? localStorage : null);
  if (storage && typeof storage.setItem === 'function') {
    storage.setItem('gev-locale', resolved);
  }

  if (typeof document !== 'undefined') {
    document.documentElement.lang = resolved;
    document.title = t('appTitle', resolved);
  }

  if (!options.skipApply) {
    const root = typeof document !== 'undefined' ? document : null;
    if (root) applyTranslations(root, resolved);
  }

  if (typeof window !== 'undefined' && typeof window.dispatchEvent === 'function') {
    window.dispatchEvent(new CustomEvent('gev:localechange', { detail: { locale: resolved } }));
  }

  return resolved;
}

export function t(key, locale = currentLocale) {
  const resolved = resolveLocale(locale);
  const dictionary = translations[resolved] ?? translations.en;
  return Object.prototype.hasOwnProperty.call(dictionary, key) ? dictionary[key] : translations.en[key] ?? key;
}

export function applyTranslations(root = typeof document !== 'undefined' ? document : null, locale = currentLocale) {
  const resolved = resolveLocale(locale);
  if (!root) return resolved;

  const targetRoot = root.documentElement ? root : root.ownerDocument || (typeof document !== 'undefined' ? document : null);
  if (targetRoot?.documentElement) targetRoot.documentElement.lang = resolved;
  if (targetRoot && targetRoot.title != null) targetRoot.title = t('appTitle', resolved);

  const elements = root.querySelectorAll ? root.querySelectorAll('[data-i18n]') : [];
  for (const element of elements) {
    const key = element.dataset?.i18n;
    if (!key) continue;
    const value = t(key, resolved);
    const labelTarget = element.querySelector ? element.querySelector('[data-language-label]') : null;
    if (element.matches?.('[data-language-menu-trigger]')) {
      if (labelTarget && typeof value === 'string') labelTarget.textContent = value;
      continue;
    }
    if (typeof value === 'string' && element.textContent !== value) element.textContent = value;
  }

  const labels = root.querySelectorAll ? root.querySelectorAll('[data-i18n-label]') : [];
  for (const element of labels) {
    const key = element.dataset?.i18nLabel;
    if (!key) continue;
    const value = t(key, resolved);
    if (typeof value === 'string') element.setAttribute('aria-label', value);
    if (element.dataset?.i18nText === 'true' && typeof value === 'string') {
      element.textContent = value;
    }
  }

  const menuTrigger = root.querySelector ? root.querySelector('[data-language-menu-trigger]') : null;
  const menuTriggerLabel = menuTrigger ? menuTrigger.querySelector('[data-language-label]') : null;
  if (menuTriggerLabel) menuTriggerLabel.textContent = t('language', resolved);
  else if (menuTrigger) menuTrigger.textContent = t('language', resolved);

  const menuLabel = root.querySelector ? root.querySelector('[data-language-menu-label]') : null;
  if (menuLabel) menuLabel.textContent = t('selectLanguage', resolved);

  const localeButtons = root.querySelectorAll ? root.querySelectorAll('[data-locale]') : [];
  for (const button of localeButtons) {
    const selected = resolveLocale(button.dataset.locale) === resolved;
    button.setAttribute('aria-checked', String(selected));
    button.setAttribute('aria-pressed', String(selected));
  }

  currentLocale = resolved;
  return resolved;
}

export function initializeLocale(storage = typeof localStorage !== 'undefined' ? localStorage : null) {
  let resolved = 'en';
  if (storage && typeof storage.getItem === 'function') {
    const saved = storage.getItem('gev-locale');
    resolved = saved ? resolveLocale(saved) : 'en';
  }
  return setLocale(resolved, { storage, skipApply: false });
}

export function bindLanguageControls(root = document) {
  const controls = root.querySelectorAll ? root.querySelectorAll('[data-locale]') : [];
  const menuTrigger = root.querySelector ? root.querySelector('[data-language-menu-trigger]') : null;
  const menu = root.querySelector ? root.querySelector('[data-language-menu]') : null;

  if (!menu || !menuTrigger) return;

  const closeMenu = () => {
    menu.hidden = true;
    menu.style.display = 'none';
    menuTrigger.setAttribute('aria-expanded', 'false');
    menuTrigger.setAttribute('aria-pressed', 'false');
  };

  const openMenu = () => {
    menu.hidden = false;
    menu.style.display = 'flex';
    menuTrigger.setAttribute('aria-expanded', 'true');
    menuTrigger.setAttribute('aria-pressed', 'true');
  };

  menuTrigger.addEventListener('click', (event) => {
    event.stopPropagation();
    if (menu.hidden) openMenu();
    else closeMenu();
  });

  for (const control of controls) {
    const locale = control.dataset.locale;
    if (!locale) continue;
    const selected = resolveLocale(locale) === currentLocale;
    control.setAttribute('aria-checked', String(selected));
    control.setAttribute('aria-pressed', String(selected));
    control.addEventListener('click', (event) => {
      event.stopPropagation();
      setLocale(locale);
      closeMenu();
      for (const button of controls) {
        const isActive = resolveLocale(button.dataset.locale) === currentLocale;
        button.setAttribute('aria-checked', String(isActive));
        button.setAttribute('aria-pressed', String(isActive));
      }
    });
  }

  document.addEventListener('click', (event) => {
    const target = event.target;
    if (target && !menu.contains(target) && !menuTrigger.contains(target)) {
      closeMenu();
    }
  });

  closeMenu();
}

